-- One-time DDL for the modernized EHRP2BIIS pipeline (run by a DBA in NKNIGHT).
-- Staging tables receive the Databricks silver slice; the run ledger makes the
-- non-idempotent black-box HISTDBA steps safe to rerun.

CREATE TABLE NKNIGHT.STG_NWK_ACTION_PRIMARY_TBL AS SELECT * FROM NKNIGHT.NWK_ACTION_PRIMARY_TBL WHERE 1 = 0
/
CREATE TABLE NKNIGHT.STG_NWK_ACTION_SECONDARY_TBL AS SELECT * FROM NKNIGHT.NWK_ACTION_SECONDARY_TBL WHERE 1 = 0
/
CREATE TABLE NKNIGHT.STG_EHRP_RECS_TRACKING_TBL AS SELECT * FROM NKNIGHT.EHRP_RECS_TRACKING_TBL WHERE 1 = 0
/
CREATE TABLE NKNIGHT.EHRP2BIIS_RUN_LEDGER (
    LOAD_ID       VARCHAR2(10)  NOT NULL,
    STEP_NAME     VARCHAR2(64)  NOT NULL,
    COMPLETED_AT  DATE          DEFAULT SYSDATE NOT NULL,
    AIRFLOW_RUN   VARCHAR2(250),
    CONSTRAINT EHRP2BIIS_RUN_LEDGER_PK PRIMARY KEY (LOAD_ID, STEP_NAME)
)
/
