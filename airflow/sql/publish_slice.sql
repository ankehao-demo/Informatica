-- Swap the Databricks output for one load into the Oracle work tables that the
-- HISTDBA afterload procedures read. Delete + insert of the same slice inside one
-- transaction => rerunnable. Binds: :load_id ('NK'||yyyymmdd), :load_date ('YYYY-MM-DD').
DELETE FROM NKNIGHT.NWK_ACTION_SECONDARY_TBL
 WHERE EVENT_ID IN (SELECT EVENT_ID FROM NKNIGHT.NWK_ACTION_PRIMARY_TBL WHERE LOAD_ID = :load_id
                    UNION SELECT EVENT_ID FROM NKNIGHT.STG_NWK_ACTION_PRIMARY_TBL)
/
DELETE FROM NKNIGHT.NWK_ACTION_PRIMARY_TBL WHERE LOAD_ID = :load_id
/
DELETE FROM NKNIGHT.EHRP_RECS_TRACKING_TBL
 WHERE LOAD_DATE = TO_DATE(:load_date, 'YYYY-MM-DD')
   AND BIIS_EVENT_ID IN (SELECT BIIS_EVENT_ID FROM NKNIGHT.STG_EHRP_RECS_TRACKING_TBL)
/
INSERT INTO NKNIGHT.NWK_ACTION_SECONDARY_TBL SELECT * FROM NKNIGHT.STG_NWK_ACTION_SECONDARY_TBL
/
INSERT INTO NKNIGHT.NWK_ACTION_PRIMARY_TBL SELECT * FROM NKNIGHT.STG_NWK_ACTION_PRIMARY_TBL WHERE LOAD_ID = :load_id
/
INSERT INTO NKNIGHT.EHRP_RECS_TRACKING_TBL SELECT * FROM NKNIGHT.STG_EHRP_RECS_TRACKING_TBL
 WHERE LOAD_DATE = TO_DATE(:load_date, 'YYYY-MM-DD')
/
